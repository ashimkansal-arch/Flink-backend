-- Persist CRM geofence form fields on coverage_zones (radius + polygon).
ALTER TABLE "coverage_zones"
  ADD COLUMN IF NOT EXISTS "zone_type" VARCHAR(40) NOT NULL DEFAULT 'Service Zone',
  ADD COLUMN IF NOT EXISTS "boundary_mode" VARCHAR(20) NOT NULL DEFAULT 'radius',
  ADD COLUMN IF NOT EXISTS "state" VARCHAR(80),
  ADD COLUMN IF NOT EXISTS "address" VARCHAR(500),
  ADD COLUMN IF NOT EXISTS "center_lat" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "center_lng" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "radius_km" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "radius_meters" INTEGER,
  ADD COLUMN IF NOT EXISTS "updated_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP;
